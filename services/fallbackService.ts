/**
 * Intelligent Fallback Lesson Generator when Gemini returns 403 or is unavailable.
 */
export const getFallbackLesson = (topic: string, grade: string, includeContext: boolean = false): GeneratedLesson => {
  const cleanTitle = cleanTopicName(topic);
  const boardPlan = getFallbackBoardPlan(topic, grade);
  
  let contextualSection = "";
  if (includeContext) {
    contextualSection = `
### 🌍 Математика околу нас
Математичките концепти од наставната единица **${cleanTitle}** се присутни во секојдневниот живот: при планирање на буџет, видео игри, архитектура, дизајн и спортски анализи. Разбирањето на овие законитости им овозможува на учениците брзо и логично решавање на реални животни проблеми.
`;
  }

  return {
    title: cleanTitle,
    objectives: [
      `Учениците да ги разберат основните поими и дефиниции за ${cleanTitle}.`,
      `Учениците да ги применуваат соодветните математички формули и постапки за ${grade} одделение.`,
      `Учениците да развијат вештини за логичко заклучување и решавање проблеми од секојдневниот живот.`
    ],
    content: `${boardPlan}

${contextualSection}

### 📝 Задачи за вежбање
1. Реши ја стандардната задача од оваа наставна единица според разработените примери.
2. Објасни ја постапката и образложи го добиениот резултат.

### 🏠 Предлог за домашна работа
1. Задача 1: Пресметај според дадените вредности во тетратката.
2. Задача 2: Примени ги формулите на реален текстуален проблем.
---
### 🔑 Решенија (Само за наставникот)
1. Решение со чекор-по-чекор постапка.
2. Анализа на точниот резултат.`
  };
};

