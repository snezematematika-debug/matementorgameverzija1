/**
 * Clean up topic string (e.g., "1.1. Релации меѓу множества" -> "Релации меѓу множества")
 */
export const cleanTopicName = (topic: string): string => {
  return topic.replace(/^\d+(\.\d+)*\.?\s*/, '').trim();
};

